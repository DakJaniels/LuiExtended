--- @class (partial) LUIE.ChatAnnouncements
local ChatAnnouncements = LUIE.ChatAnnouncements

local function BuildPrimaryTextLookup(stringIds)
    local lookup = {}
    for index = 1, #stringIds do
        lookup[GetString(stringIds[index])] = true
    end
    return lookup
end

